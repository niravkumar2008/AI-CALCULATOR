// Static checks for every page in web/site (no dependencies):
//   node web/tools/check-site.mjs
// - balanced tags, unique ids, every for= / aria-*by= / href="#id" / <use href="#id"> resolves
// - every internal link points at a page or file that exists
// - every <img> has width, height and alt
// - shared chrome is up to date (same as chrome.mjs --check)
// - marketing copy never names an AI vendor or the plumbing (privacy/terms are exempt)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';

const here = path.dirname(fileURLToPath(import.meta.url));
const SITE = path.resolve(here, '../site');
const VOID = new Set(['area', 'base', 'br', 'col', 'embed', 'hr', 'img', 'input', 'link', 'meta', 'source', 'track', 'wbr', 'use', 'path', 'rect', 'circle', 'stop']);
const EXEMPT_COPY = new Set(['/privacy/', '/terms/']);
const FORBIDDEN = /\b(anthropic|claude|api key|stripe|openai|chatgpt|our server)\b/i;

function pages(dir) {
  const out = [];
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) {
      if (e.name !== 'assets' && e.name !== 'try') out.push(...pages(p));
    } else if (e.name.endsWith('.html')) out.push(p);
  }
  return out;
}
const urlOf = (f) => {
  const r = path.relative(SITE, f).split(path.sep).join('/');
  return r === 'index.html' ? '/' : r.endsWith('/index.html') ? '/' + r.slice(0, -10) : '/' + r;
};
function exists(urlPath) {
  const p = decodeURIComponent(urlPath.split(/[?#]/)[0]);
  if (p.startsWith('/api/') || p.startsWith('/__dev/')) return true;
  const f = path.join(SITE, p);
  if (p.endsWith('/')) return fs.existsSync(path.join(f, 'index.html'));
  return fs.existsSync(f) || fs.existsSync(path.join(f, 'index.html'));
}

let problems = 0;
const report = (file, msg) => {
  problems++;
  console.log(`${urlOf(file)}: ${msg}`);
};

for (const file of pages(SITE)) {
  const html = fs.readFileSync(file, 'utf8');
  const body = html.replace(/<script\b[\s\S]*?<\/script>/g, '').replace(/<style\b[\s\S]*?<\/style>/g, '').replace(/<!--[\s\S]*?-->/g, '').replace(/<template\b[\s\S]*?<\/template>/g, '');
  // balanced tags
  const stack = [];
  for (const m of body.matchAll(/<\/?([a-zA-Z][\w-]*)\b[^>]*?(\/?)>/g)) {
    const tag = m[1].toLowerCase();
    if (VOID.has(tag) || m[2] === '/') continue;
    if (m[0].startsWith('</')) {
      if (stack.at(-1) === tag) stack.pop();
      else {
        report(file, `unbalanced </${tag}> (open: ${stack.slice(-3).join('>')})`);
        break;
      }
    } else stack.push(tag);
  }
  if (stack.length) report(file, `unclosed: ${stack.slice(-4).join('>')}`);
  // ids
  const ids = [...html.matchAll(/\sid="([^"]+)"/g)].map((m) => m[1]);
  const seen = new Set();
  for (const id of ids) {
    if (seen.has(id)) report(file, `duplicate id "${id}"`);
    seen.add(id);
  }
  for (const m of html.matchAll(/\s(?:for|aria-labelledby|aria-describedby|aria-controls)="([^"]+)"/g)) {
    for (const id of m[1].split(/\s+/)) if (!seen.has(id)) report(file, `reference to missing id "${id}"`);
  }
  for (const m of html.matchAll(/<use href="#([^"]+)"/g)) if (!seen.has(m[1])) report(file, `missing icon #${m[1]}`);
  // links
  for (const m of html.matchAll(/\s(?:href|src|srcset|action)="([^"]+)"/g)) {
    for (const raw of m[1].split(',').map((x) => x.trim().split(/\s+/)[0])) {
      if (!raw || /^(https?:|mailto:|tel:|data:|#|javascript:)/.test(raw)) continue;
      const abs = raw.startsWith('/') ? raw : new URL(raw, 'http://x' + urlOf(file)).pathname;
      if (!exists(abs)) report(file, `broken link ${raw}`);
    }
  }
  // images
  for (const m of html.matchAll(/<img\b[^>]*>/g)) {
    if (!/\swidth="\d+"/.test(m[0]) || !/\sheight="\d+"/.test(m[0])) report(file, `img without width/height: ${m[0].slice(0, 80)}`);
    if (!/\salt="/.test(m[0])) report(file, `img without alt: ${m[0].slice(0, 80)}`);
  }
  // copy rule
  if (!EXEMPT_COPY.has(urlOf(file))) {
    const text = body.replace(/<[^>]+>/g, ' ');
    const hit = FORBIDDEN.exec(text);
    if (hit) report(file, `copy mentions "${hit[0]}" (keep vendors and plumbing private)`);
  }
  if ((html.match(/<h1\b/g) || []).length !== 1) report(file, `expected exactly one <h1>`);
}

// The simulator (try/) is generated by sim/web/make_embed.py and has no shared chrome, but it is
// public too: no vendor name anywhere in it, page source included.
{
  const sim = path.join(SITE, 'try', 'index.html');
  const hit = fs.existsSync(sim) && /claude|anthropic|sk-ant|openai|stripe/i.exec(fs.readFileSync(sim, 'utf8'));
  if (hit) report(sim, `simulator names "${hit[0]}" (rebuild with python sim/web/make_embed.py)`);
}

try {
  execFileSync(process.execPath, [path.join(here, 'chrome.mjs'), '--check'], { stdio: 'pipe' });
} catch (e) {
  problems++;
  console.log(String(e.stdout || e.message).trim());
}
console.log(problems ? `\n${problems} problem(s)` : 'site check: all good');
process.exit(problems ? 1 : 0);
